"""Writes docs/REFERENCES.md from knowledge/graph.json: every source, a search link to find it,
and which cause-and-effect links in the graph rely on it."""
import json
import re
from collections import defaultdict
from pathlib import Path
from urllib.parse import quote_plus

ROOT = Path(__file__).resolve().parents[1]
g = json.loads((ROOT / "knowledge" / "graph.json").read_text())
label = {n["id"]: n["label"] for n in g["nodes"]}
used = defaultdict(list)
for e in g["edges"]:
    for r in e["refs"]:
        used[r].append(f"{label[e['source']]} → {label[e['target']]} ({e['grade']})")
for s in g["signals"]:
    for r in s["refs"]:
        used[r].append(f"signal: {s['rule']}")
for f in g["redFlags"]:
    for r in f["refs"]:
        used[r].append(f"red flag: {f['text']}")

SITES = {"who": "https://www.who.int/publications", "eau2024": "https://uroweb.org/guidelines/sexual-and-reproductive-health",
         "ada2024": "https://diabetesjournals.org/care/issue/47/Supplement_1", "idf2006": "https://idf.org/",
         "ceh2022": "https://www.ceh.org/", "adphc_ifhas2025": "https://www.ifhas.gov.ae",
         "uae_law2_2019": "https://u.ae/en/about-the-uae/digital-uae/data/data-protection-laws", "adhics": "https://www.doh.gov.ae/en/resources/standards"}


def link(key, text):
    if key.startswith("u_"):
        return None
    for k, url in SITES.items():
        if key.startswith(k):
            return url
    m = re.match(r"(.+?)\s*\((\d{4})\)\.\s*(.+?)\.", text)
    q = f"{m.group(1).split(',')[0].split(' et al')[0]} {m.group(3)}" if m else text[:120]
    return "https://pubmed.ncbi.nlm.nih.gov/?term=" + quote_plus(q)


lines = ["# References", "",
         f"Every link in the evidence graph cites at least one of these {len(g['references'])} sources. "
         "Journal articles link to a PubMed search for the exact title; guidelines and reports link to the publisher. "
         "Generated by `scripts/make_refs.py` from `knowledge/graph.json`.", "",
         "| Source | Used for |", "|---|---|"]
for key, text in sorted(g["references"].items(), key=lambda kv: kv[1]):
    url = link(key, text)
    src = f"[{text}]({url})" if url else f"{text} *(team's own source, full citation pending)*"
    uses = used.get(key, [])
    shown = "<br>".join(uses[:4]) + (f"<br>…and {len(uses) - 4} more" if len(uses) > 4 else "")
    lines.append(f"| {src} | {shown or 'background'} |")
(ROOT / "docs" / "REFERENCES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(len(g["references"]), "references")
